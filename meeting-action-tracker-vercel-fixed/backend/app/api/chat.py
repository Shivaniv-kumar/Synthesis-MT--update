"""Meeting data chatbot endpoint.

POST /api/chat/message — ask a question about the workspace's meeting transcripts
and action items. The answer is generated by Claude using the stored data as context.

POST /api/chat/share  — forward a chat response to email, Teams, or Slack.
"""

from __future__ import annotations

